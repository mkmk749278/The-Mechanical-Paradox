// Export a film's SFX cues (picture code is the single source) to films/<slug>/sound/sfx.json for score_mix.py.
// Usage: node scripts/export_cues.mjs films/<slug> <module exporting filmCues()>
import {build} from 'esbuild';
import {writeFileSync, mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const [film, mod] = process.argv.slice(2);
const out = resolve('.cache/cues.mjs');
mkdirSync('.cache', {recursive: true});
await build({entryPoints: [resolve(mod)], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error',
	jsx: 'automatic', loader: {'.ts': 'ts', '.tsx': 'tsx'},
	define: {'process.env.NODE_ENV': '"production"'}});
globalThis.window = globalThis.window ?? undefined;
const m = await import(pathToFileURL(out).href);
const t = (await import(pathToFileURL(resolve(film, 'vo/timing.json')).href, {with: {type: 'json'}})).default;
const cues = m.filmCues().map((c) => ({at: +(c.frame / t.fps).toFixed(3), sfx: c.sfx, gain_db: c.gainDb, pan: c.pan ?? 0}));
cues.sort((a, b) => a.at - b.at);
writeFileSync(resolve(film, 'sound/sfx.json'), JSON.stringify({note: 'generated by scripts/export_cues.mjs from the picture code', cues}, null, 1) + '\n');
console.log(`${cues.length} cues → ${film}/sound/sfx.json`);
