"""Generate lib/remotion/brand.ts from config/brand.yaml (PLAYBOOK §10.2: scenes never type a colour by hand).
Run: python3 scripts/brand_ts.py"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
b = yaml.safe_load((ROOT / "config/brand.yaml").read_text())


def obj(d: dict) -> str:
    return "{\n" + "".join(f"  {k}: {v!r},\n".replace("'", "'") for k, v in d.items()) + "}"


out = ["// Generated by scripts/brand_ts.py from config/brand.yaml. Do not edit by hand.", ""]
out.append(f"export const colors = {obj(b['colors'])} as const;\n")
out.append(f"export const feaRamp = {b['fea_ramp']!r} as const;\n")
out.append(f"export const fonts = {obj(b['fonts'])} as const;\n")
out.append(f"export const video = {obj(b['video'])} as const;\n")
out.append(f"export const physicalSpring = {obj(b['spring'])} as const;\n")
out.append(f"export const channel = {obj({'name': b['channel_name'], 'handle': b['handle'], 'tagline': b['tagline']})} as const;")
(ROOT / "lib/remotion/brand.ts").write_text("\n".join(out) + "\n")
print("wrote lib/remotion/brand.ts")
